#!/usr/bin/env python3
"""Embed the workspace backup module (W6) into the tool's HTML file.   python workspace-backup/embed.py [--check]

The block is placed just before the tool's own main script so it runs FIRST: a restore that was parked before a reload is re-applied before the tool reads any
saved data. The shared module (workspace-backup.js) must be identical in both repositories: its SHA-256 is recorded in LOCK.sha256 and checked here.
"""
import hashlib
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(HERE, "config.json"), encoding="utf-8"))
HTML = os.path.normpath(os.path.join(HERE, CFG["html"]))
BEGIN = "<!-- WORKSPACE-BACKUP:BEGIN (generated by workspace-backup/embed.py; do not edit by hand) -->"
END = "<!-- WORKSPACE-BACKUP:END -->"


def read(path):
    with open(path, encoding="utf-8", newline="") as f:
        return f.read().replace("\r\n", "\n")


def sha(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def block():
    shared = read(os.path.join(HERE, "workspace-backup.js"))
    adapter = read(os.path.join(HERE, "adapter.js"))
    for name, t in (("workspace-backup.js", shared), ("adapter.js", adapter)):
        if "</script" in t.lower():
            sys.exit(f"{name} contains a closing script tag; cannot embed")
    boot = (
        ";(function(){\n"
        "  var adapter = (function(){\n" + adapter + "\n  return WB_ADAPTER;\n  })();\n"
        "  WorkspaceBackup.configure(adapter);\n"
        "  WorkspaceBackup.applyPending();\n"
        "  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', WorkspaceBackup.mount); else WorkspaceBackup.mount();\n"
        "})();\n"
    )
    return BEGIN + '\n<script id="workspace-backup">\n' + shared + "\n" + boot + "</script>\n" + END + "\n"


def lock_ok():
    lock = os.path.join(HERE, "LOCK.sha256")
    want = read(lock).split()[0] if os.path.exists(lock) else ""
    got = sha(read(os.path.join(HERE, "workspace-backup.js")))
    return want == got, want, got


def embedded(html):
    m = re.search(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", html, re.S)
    return m


def main():
    check = "--check" in sys.argv
    ok, want, got = lock_ok()
    if not ok:
        if check or "--relock" not in sys.argv:
            sys.exit(f"shared module differs from LOCK.sha256 (locked {want[:12] or 'none'}, now {got[:12]}). If the change is intended, apply it to BOTH repositories and run with --relock.")
        open(os.path.join(HERE, "LOCK.sha256"), "w", encoding="utf-8", newline="\n").write(got + "  workspace-backup.js\n")
        print("lock updated:", got[:12])
    html = read(HTML)
    new = block()
    m = embedded(html)
    if check:
        if not m or m.group(0) != new:
            sys.exit("workspace-backup block in the tool is missing or out of date: run python workspace-backup/embed.py")
        print("workspace-backup block is up to date")
        return
    if m:
        html = html[:m.start()] + new + html[m.end():]
    else:
        a = re.search(CFG["anchorRegex"], html, re.M)
        if not a:
            sys.exit("anchor for the tool's main script not found")
        html = html[:a.start()] + new + html[a.start():]
    tmp = HTML + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write(html)
    os.replace(tmp, HTML)
    print("embedded workspace backup into", os.path.basename(HTML), f"({len(new) // 1024} KB block)")


if __name__ == "__main__":
    main()
